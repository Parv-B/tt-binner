"""Markdown report assembly for a BINNER ``analyze()`` result.

Pure text/formatting; no statistics live here (that's binner_analysis.py) and no
plotting (that's plots.py). ``build_report(R, figs, validation=None)`` returns the
full Markdown string; ``run_analysis.py`` writes it to disk next to the figures.
"""
from __future__ import annotations

import math

import numpy as np
import pandas as pd

import binner_analysis as ba


def _fmt(v, sig=4):
    if v is None:
        return "n/a"
    if isinstance(v, (list, tuple)):
        if len(v) == 2 and all(isinstance(x, (int, float, np.floating)) for x in v):
            return f"[{_fmt(v[0])}, {_fmt(v[1])}]"
        return str(v)
    if isinstance(v, (float, np.floating)):
        if not np.isfinite(v):
            return "n/a"
        return f"{v:.{sig}g}"
    if isinstance(v, bool):
        return "PASS" if v else "FAIL"
    return str(v)


def df_to_md(df: pd.DataFrame, cols=None, rename=None, float_sig=4, index_name=None) -> str:
    """Minimal, dependency-free DataFrame -> GitHub-flavoured Markdown table.

    ``cols`` selects/orders *actual* DataFrame column names (applied after the
    index is turned into a column, so ``index_name`` can appear in it too).
    ``rename`` maps actual column names to display headers; columns not in
    ``rename`` keep their own name as the header. Keeping selection (``cols``)
    and display labels (``rename``) tied to real column names -- instead of a
    free-standing header list -- avoids silently misaligned tables when a
    column is added/removed upstream.
    """
    if df is None or not len(df):
        return "_(no data)_\n"
    d = df.copy()
    if index_name:
        d = d.reset_index().rename(columns={d.index.name or "index": index_name})
    elif d.index.name:
        d = d.reset_index()
    if cols:
        missing = [c for c in cols if c not in d.columns]
        if missing:
            raise KeyError(f"df_to_md: requested cols not present: {missing} (have {list(d.columns)})")
        d = d[cols]
    rename = rename or {}
    hdrs = [rename.get(c, c) for c in d.columns]
    lines = ["| " + " | ".join(str(h) for h in hdrs) + " |",
             "|" + "|".join(["---"] * len(hdrs)) + "|"]
    for _, row in d.iterrows():
        cells = []
        for v in row.values:
            if v is None or (isinstance(v, float) and math.isnan(v)):
                cells.append("n/a")
            elif isinstance(v, (list, tuple, np.ndarray)):
                cells.append(_fmt(list(v), float_sig))
            elif isinstance(v, (float, np.floating)):
                cells.append(_fmt(v, float_sig))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def _section(title, level=2):
    return f"\n{'#' * level} {title}\n"


def _fig(figs, key, caption):
    if key not in figs:
        return ""
    return f"\n![{caption}](figures/{figs[key]})\n\n*{caption}*\n"


